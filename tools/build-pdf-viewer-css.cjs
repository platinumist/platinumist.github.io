// Run when upgrading PDF.js or changing the viewer styles.
const fs = require("node:fs");
const path = require("node:path");
const { transform } = require("lightningcss");

const directory = path.join(__dirname, "../docs/assets/pdfjs/web");
const original = fs.readFileSync(path.join(directory, "viewer.css"), "utf8").replace(/\r\n/g, "\n");
const license = original.slice(0, original.indexOf("*/") + 2);
const overrides = fs.readFileSync(path.join(directory, "viewer-overrides.css"), "utf8").replace(/\r\n/g, "\n");
const result = transform({
  filename: "viewer.css",
  code: Buffer.from(original + "\n" + overrides),
  targets: { chrome: 86 << 16, safari: (14 << 16) | (1 << 8) },
  minify: false,
});
if (result.warnings.length) {
  throw new Error(JSON.stringify(result.warnings));
}
const header = "/* Generated by tools/build-pdf-viewer-css.cjs; edit viewer.css or viewer-overrides.css. */\n";
fs.writeFileSync(path.join(directory, "viewer-compatible.css"),
  license + "\n\n" + header + result.code.toString());
